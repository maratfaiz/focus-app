import Foundation

/// Генератор длинного текста для перепечатки. Предложения намеренно
/// длинные и занудные — чтобы импульсивно разблокировать было лень.
enum RetypeTextGenerator {
    private static let sentences: [String] = [
        "Я осознанно решаю прервать блокировку, хотя ставил её сам, находясь в более трезвом состоянии ума.",
        "Каждая минута, проведённая в ленте, — это минута, отнятая у дела, которое я сам назвал важным.",
        "Привычки формируются повторением, и прямо сейчас я повторяю ту, от которой хотел избавиться.",
        "Если я печатаю этот текст на автомате, не задумываясь, значит решение открыть приложение тоже было автоматическим.",
        "Скука — это не чрезвычайная ситуация, и её не обязательно немедленно заполнять чужим контентом.",
        "Через час я вряд ли вспомню, что именно посмотрел, но точно вспомню, что ничего не успел.",
        "Сила воли ограничена, поэтому я поставил эту блокировку заранее, когда она ещё была.",
        "Телефон должен работать на мои цели, а не мои цели — на удержание внимания в телефоне.",
        "Я могу вернуться к этому приложению позже, в отведённое для отдыха время, и ничего не потеряю.",
        "Настоящий отдых — это прогулка, разговор или тишина, а не бесконечная прокрутка коротких видео.",
    ]

    static func text(sentences count: Int) -> String {
        let shuffled = sentences.shuffled()
        return shuffled.prefix(max(1, min(count, shuffled.count))).joined(separator: " ")
    }
}
